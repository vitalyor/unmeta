# Builds design/mockups/icons.js from Lucide (ISC), pinned version. Run: python3 design/tools/build_icons.py
# One set, one grid (24), one stroke (set in CSS/JS: 1.75), currentColor. Inline SVG only — no icon font, no CDN at runtime.
import json, re, urllib.request
from pathlib import Path

VER = '1.69.0'
BASE = f'https://unpkg.com/lucide-static@{VER}'
# our key -> Lucide name. Category/mode keys match the copy dictionary keys (icon is bound in markup, not in text).
MAP = {
    # categories
    'location': 'map-pin', 'device': 'smartphone', 'dates': 'clock-3', 'author': 'user-round',
    'software': 'pencil-line', 'thumbnails': 'image', 'descriptions': 'message-square-text',
    'c2pa': 'badge-check', 'filename': 'tag',
    # modes
    'shield': 'shield', 'scale': 'scale', 'private': 'eye-off', 'sliders': 'sliders-horizontal',
    # actions / statuses / chrome
    'eraser': 'eraser', 'upload': 'upload', 'download': 'download', 'share': 'share', 'check': 'check',
    'x': 'x', 'info': 'info', 'chevron': 'chevron-down', 'sun': 'sun', 'moon': 'moon', 'plus': 'plus',
    'lock': 'lock', 'arrow': 'arrow-right',
}

def get(url):
    with urllib.request.urlopen(url, timeout=20) as r:
        return r.read().decode('utf-8')

icons = {}
for key, name in MAP.items():
    svg = get(f'{BASE}/icons/{name}.svg')
    inner = re.search(r'<svg[^>]*>(.*)</svg>', svg, re.S).group(1)
    icons[key] = re.sub(r'\s+', ' ', inner).replace(' />', '/>').strip()
lic = get(f'{BASE}/LICENSE').strip()
out = Path(__file__).resolve().parent.parent / 'mockups' / 'icons.js'
out.write_text(
    f'/* Icons: Lucide v{VER} (https://lucide.dev), inner SVG elements only. Generated by design/tools/build_icons.py.\n\n'
    + lic.replace('*/', '* /') + '\n*/\n'
    + 'window.UM_ICONS = ' + json.dumps(icons, ensure_ascii=False, indent=0) + ';\n'
    + 'window.UM_ICON_SOURCE = ' + json.dumps({k: f'lucide:{v}' for k, v in MAP.items()}) + ';\n',
    encoding='utf-8')
assert len(icons) == len(MAP) and all(icons.values())
print('icons.js:', len(icons), 'icons')
